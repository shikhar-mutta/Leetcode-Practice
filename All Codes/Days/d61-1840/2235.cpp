#include <bits/stdc++.h>
using namespace std;

// TC: O(1), SC: O(1)
//   Approach:
//   1. We can simply return the sum of the two integers using the + operator
class Solution
{
public:
    int sum(int num1, int num2) { return num1 + num2; }
};